/**
 * Builds supabase/setup-all-in-one.sql for the Supabase SQL editor:
 *   npm run db:bundle
 *
 * The file is safe to run any number of times, on a fresh or an existing
 * database: each migration is wrapped in a check and only runs if its
 * objects are not there yet. (`npx supabase db push` remains the preferred
 * route when the CLI is available.)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

// How to tell that a migration has already been applied.
const PROBES = {
  '20261020000001': "to_regclass('public.region_archetypes') is not null",
  '20261020000002': "to_regprocedure('public.world_decay(numeric, timestamptz, numeric, timestamptz)') is not null",
  '20261020000003': "to_regprocedure('public.admin_overview()') is not null",
  '20261020000004': "exists (select 1 from pg_policies where schemaname = 'public' and policyname = 'archetypes are public')",
  '20261020000005': "exists (select 1 from public.regions where slug = 'the-core')",
  '20261020000006': "to_regprocedure('public.current_actor()') is not null",
};

const dir = 'supabase/migrations';
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const blocks = files.map((f) => {
  const version = f.slice(0, 14);
  const probe = PROBES[version];
  if (!probe) throw new Error(`Add an "already applied" probe for ${f} in scripts/bundle-sql.mjs`);
  const sql = readFileSync(`${dir}/${f}`, 'utf8');
  const tag = `$io_${version}$`;
  if (sql.includes(tag)) throw new Error(`${f} contains the quoting tag ${tag}`);
  return `-- ===== ${f} =====
do $io_check$
begin
  if ${probe} then
    raise notice 'Skipping ${f} (already applied)';
  else
    raise notice 'Applying ${f}';
    execute ${tag}
${sql}
${tag};
  end if;
end
$io_check$;`;
});

writeFileSync('supabase/setup-all-in-one.sql', `-- Internet Organism — complete database setup for the Supabase SQL editor.
-- Generated by scripts/bundle-sql.mjs from supabase/migrations/. Do not edit.
--
-- Safe to run again: parts that are already installed are skipped, and only
-- missing parts are added. Paste everything into SQL Editor and click Run.

${blocks.join('\n\n')}

select 'Internet Organism database is ready' as status,
       (select count(*) from public.regions) as regions,
       (select count(*) from public.feature_flags) as feature_flags;
`);
console.warn(`wrote supabase/setup-all-in-one.sql (${files.length} migrations)`);

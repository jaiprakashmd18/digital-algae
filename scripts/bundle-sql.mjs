/**
 * Concatenates all migrations into one file for the Supabase SQL editor:
 *   npm run db:bundle   →  supabase/setup-all-in-one.sql
 * Paste it into Dashboard → SQL Editor → Run (only on a fresh project).
 * Using `npx supabase db push` instead is preferred when possible.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = 'supabase/migrations';
const parts = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
  .map((f) => `-- ===== ${f} =====\n${readFileSync(`${dir}/${f}`, 'utf8')}`);
writeFileSync('supabase/setup-all-in-one.sql', `-- Generated by scripts/bundle-sql.mjs. Do not edit; edit the migrations.\n\n${parts.join('\n\n')}`);
console.warn('wrote supabase/setup-all-in-one.sql');
